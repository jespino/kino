// Generates src/core/metrics.ts: advance widths (in em) of the bundled fonts, so
// text layout is exact and identical in the browser and in the Node renderer.
//   npx tsx cli/gen-metrics.ts
import { writeFileSync } from 'node:fs';
// @ts-ignore no types shipped
import opentype from 'opentype.js';

// [family, weight, file]; a theme can use any family listed here (see theme.ts)
const FONTS: [string, number, string][] = [
  ['Inter', 400, 'Inter-Regular.ttf'],
  ['Inter', 600, 'Inter-SemiBold.ttf'],
  ['Inter', 700, 'Inter-Bold.ttf'],
  ['Inter', 800, 'Inter-ExtraBold.ttf'],
  ['JetBrains Mono', 400, 'JetBrainsMono-Regular.ttf'],
  ['JetBrains Mono', 700, 'JetBrainsMono-Bold.ttf'],
  ['Kino Hand', 400, 'KinoHand-Regular.otf'],
  ['Lato', 300, 'Lato-Light.ttf'],
  ['Lato', 400, 'Lato-Regular.ttf'],
  ['Lato', 700, 'Lato-Bold.ttf'],
  ['Lato', 900, 'Lato-Black.ttf'],
  ['Fantasque Sans Mono', 400, 'FantasqueSansMono-Regular.ttf'],
  ['Fantasque Sans Mono', 700, 'FantasqueSansMono-Bold.ttf'],
  ['Bangers', 400, 'Bangers-Regular.ttf'],
  ['Comic Neue', 400, 'ComicNeue-Regular.ttf'],
  ['Comic Neue', 700, 'ComicNeue-Bold.ttf'],
  ['Press Start 2P', 400, 'PressStart2P-Regular.ttf'],
  ['VT323', 400, 'VT323-Regular.ttf'],
  ['Fredoka', 400, 'Fredoka-Regular.ttf'],
  ['Fredoka', 600, 'Fredoka-SemiBold.ttf'],
  ['Fredoka', 700, 'Fredoka-Bold.ttf'],
];
const EXTRA = '•·→←↑↓✓✗…—–“”‘’×÷≤≥≠°€£¡¿áéíóúñçüö²³';
const chars = [...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)), ...EXTRA];

const out: Record<string, number[]> = {};
for (const [family, weight, file] of FONTS) {
  const font = opentype.loadSync(`assets/fonts/${file}`);
  // -1: the font has no glyph for it, the renderer falls back to another font
  out[`${family}|${weight}`] = chars.map((c) => {
    const g = font.charToGlyph(c);
    return g.index === 0 ? -1 : +(g.advanceWidth / font.unitsPerEm).toFixed(4);
  });
}
writeFileSync(
  'src/core/metrics.ts',
  `// Generated by cli/gen-metrics.ts from assets/fonts. Do not edit.\n` +
    `export const CHARS = ${JSON.stringify(chars.join(''))};\n` +
    `export const WIDTHS: Record<string, number[]> = ${JSON.stringify(out)};\n`,
);
console.log('wrote src/core/metrics.ts');
