// Generates src/core/grain.ts: a seamless paper-grain tile (PNG, base64) that
// paper themes lay over the whole frame. Rendering the noise once and tiling it
// is far cheaper than an SVG turbulence filter on every frame.
//   npx tsx cli/gen-grain.ts
import { writeFileSync } from 'node:fs';
import { Resvg } from '@resvg/resvg-js';

const SIZE = 160;
const svg =
  `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}">` +
  `<filter id="g" x="0" y="0" width="100%" height="100%">` +
  `<feTurbulence type="fractalNoise" baseFrequency="0.75" numOctaves="2" seed="4" stitchTiles="stitch"/>` +
  // brownish speckles; alpha from the noise, most of the tile transparent
  `<feColorMatrix type="matrix" values="0 0 0 0 0.38  0 0 0 0 0.33  0 0 0 0 0.26  0 0 0 1.3 -0.58"/>` +
  `</filter><rect width="${SIZE}" height="${SIZE}" filter="url(#g)"/></svg>`;
const png = new Resvg(svg).render().asPng();
writeFileSync(
  'src/core/grain.ts',
  `// Generated by cli/gen-grain.ts. Do not edit.\n` +
    `export const GRAIN_SIZE = ${SIZE};\n` +
    `export const GRAIN_PNG = 'data:image/png;base64,${Buffer.from(png).toString('base64')}';\n`,
);
console.log(`wrote src/core/grain.ts (${png.length} bytes)`);
